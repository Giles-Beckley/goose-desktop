import { NavLink } from 'react-router-dom';
import { useConnectionStore } from '../stores/connectionStore';

interface NavItem {
  to: string;
  label: string;
  icon: () => JSX.Element;
  requiresLicense?: boolean;
  requiresLocations?: boolean;
}

const navItems: NavItem[] = [
  { to: '/', label: 'Dashboard', icon: DashboardIcon },
  { to: '/assistant', label: 'Assistant', icon: AssistantIcon, requiresLicense: true },
  { to: '/products', label: 'Products', icon: ProductsIcon },
  { to: '/orders', label: 'Orders', icon: OrdersIcon },
  { to: '/customers', label: 'Customers', icon: CustomersIcon },
  { to: '/locations', label: 'Locations', icon: LocationsIcon, requiresLocations: true },
  { to: '/exports', label: 'Exports', icon: ExportsIcon },
  { to: '/discounts', label: 'Discounts', icon: DiscountsIcon },
  { to: '/settings', label: 'Settings', icon: SettingsIcon },
];

export function Sidebar() {
  const { licenseValid, locationsEnabled } = useConnectionStore();
  // Hide items behind a feature gate only once we've definitively detected it's off
  const visibleItems = navItems.filter(
    (item) => !(item.requiresLocations && locationsEnabled === false),
  );

  return (
    <aside className="w-60 flex flex-col h-full" style={{ backgroundColor: '#1E293B' }}>
      <div className="px-5 py-5 border-b border-white/10">
        <h1 className="text-lg font-display font-bold tracking-tight" style={{ color: '#FFCC00' }}>Goose Commerce</h1>
        <p className="text-xs text-white/50 mt-0.5">Desktop Manager</p>
      </div>

      <nav className="flex-1 py-4">
        <ul className="space-y-0.5 px-3">
          {visibleItems.map((item) => {
            const disabled = item.requiresLicense && !licenseValid;

            if (disabled) {
              return (
                <li key={item.to}>
                  <NavLink
                    to={item.to}
                    className="flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium text-white/30 cursor-default"
                  >
                    <item.icon />
                    {item.label}
                  </NavLink>
                </li>
              );
            }

            return (
              <li key={item.to}>
                <NavLink
                  to={item.to}
                  end={item.to === '/'}
                  className={({ isActive }) =>
                    `flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors ${
                      isActive
                        ? 'bg-primary-600 text-white shadow-sm'
                        : 'text-white/70 hover:bg-white/8 hover:text-white'
                    }`
                  }
                >
                  <item.icon />
                  {item.label}
                </NavLink>
              </li>
            );
          })}
        </ul>
      </nav>

      <div className="px-5 py-4 border-t border-white/10">
        <p className="text-xs text-white/30">v{__APP_VERSION__}</p>
      </div>
    </aside>
  );
}

